// Generates src/core/gamedata/generated.ts from the C# source in ref/.
// The enums come from ref/decompiled/VTClassic/*.cs, the tables from the
// GameInfo class in ref/shared/Constants.cs. Run with `npm run gen`.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = new URL('../', import.meta.url)
const read = (path: string) => readFileSync(fileURLToPath(new URL(path, root)), 'utf8')

type Pair = [string, number]

// Reads one enum body. A member without `= value` continues from the last value.
function parseEnum(source: string, name: string): Pair[] {
  const match = new RegExp(`enum\\s+${name}\\s*\\{([^}]*)\\}`).exec(source)
  if (!match || !match[1]) throw new Error(`enum ${name} not found in the source`)
  const out: Pair[] = []
  let next = 0
  for (const line of match[1].split('\n')) {
    const member = /^\s*(\w+)\s*(?:=\s*(\d+))?\s*,?\s*$/.exec(line)
    if (!member || !member[1]) continue
    const value = member[2] === undefined ? next : Number(member[2])
    out.push([member[1], value])
    next = value + 1
  }
  return out
}

// Returns the body of one method, by brace matching.
function methodBody(source: string, name: string): string {
  const start = source.indexOf(`${name}(`)
  if (start < 0) throw new Error(`method ${name} not found in the source`)
  const open = source.indexOf('{', start)
  let depth = 0
  for (let i = open; i < source.length; i++) {
    if (source[i] === '{') depth++
    else if (source[i] === '}' && --depth === 0) return source.slice(open + 1, i)
  }
  throw new Error(`method ${name} body is not closed`)
}

// Fails when a `.Add` call stayed unparsed, so a table cannot lose an entry.
function expectAllParsed(body: string, parsed: number): void {
  const found = body.match(/\.Add\(/g)?.length ?? 0
  if (found !== parsed) throw new Error(`parsed ${parsed} of ${found} .Add calls`)
}

// Reads `.Add("name", 123);` calls, in source order. A value of `i--` uses the
// counter declared in the body (`int i = 32;`), like the C# code does.
function addPairs(body: string): Pair[] {
  const counters = new Map<string, number>()
  for (const decl of body.matchAll(/int\s+(\w+)\s*=\s*(\d+)\s*;/g)) counters.set(decl[1]!, Number(decl[2]!))
  const out: Pair[] = []
  for (const match of body.matchAll(/\.Add\(\s*("(?:[^"\\]|\\.)*")\s*,\s*([^,)]*?)\s*\)/g)) {
    const name = JSON.parse(match[1]!)
    const expr = match[2]!.trim()
    const literal = /^\d+$/.exec(expr)
    if (literal) {
      out.push([name, Number(literal[0])])
      continue
    }
    const counter = /^(\w+)\s*(--|\+\+)?$/.exec(expr)
    const current = counter ? counters.get(counter[1]!) : undefined
    if (!counter || current === undefined) throw new Error(`unsupported value "${expr}" for ${name}`)
    out.push([name, current])
    counters.set(counter[1]!, current + (counter[2] === '++' ? 1 : -1))
  }
  expectAllParsed(body, out.length)
  return out
}

// Reads `.Add("name", new int[] { 1, 2 });` calls, in source order.
function addGroups(body: string): Array<[string, number[]]> {
  const out: Array<[string, number[]]> = []
  for (const match of body.matchAll(/\.Add\(\s*("(?:[^"\\]|\\.)*")\s*,\s*new int\[\]\s*\{([^}]*)\}\s*\)/g))
    out.push([
      JSON.parse(match[1]!),
      match[2]!.split(',').map((s) => Number(s.trim())).filter((n) => !Number.isNaN(n)),
    ])
  expectAllParsed(body, out.length)
  return out
}

const enumText = (name: string, pairs: Pair[]) =>
  `export const ${name} = {\n${pairs.map(([key, value]) => `  ${key}: ${value},`).join('\n')}\n} as const\n`

const pairTableText = (name: string, pairs: Pair[]) =>
  `export const ${name}: ReadonlyArray<readonly [string, number]> = [\n` +
  pairs.map(([key, value]) => `  [${JSON.stringify(key)}, ${value}],`).join('\n') +
  `\n]\n`

const nameTableText = (name: string, pairs: Array<[number, string]>) =>
  `export const ${name}: ReadonlyArray<readonly [number, string]> = [\n` +
  pairs.map(([key, value]) => `  [${key}, ${JSON.stringify(value)}],`).join('\n') +
  `\n]\n`

const groupTableText = (name: string, groups: Array<[string, number[]]>) =>
  `export const ${name}: ReadonlyArray<readonly [string, readonly number[]]> = [\n` +
  groups.map(([key, ids]) => `  [${JSON.stringify(key)}, [${ids.join(', ')}]],`).join('\n') +
  `\n]\n`

const vtclassic = (file: string) => read(`ref/decompiled/VTClassic/${file}`)
const constants = read('ref/shared/Constants.cs')

const materialIds = addPairs(methodBody(constants, 'GenerateMaterialInfo'))
const materialNames: Array<[number, string]> = materialIds
  .map(([name, id]): [number, string] => [id, name])
  .sort((a, b) => a[0] - b[0])

const output = `// Generated by scripts/gen-gamedata.ts from the C# source in ref/. Do not edit.
// Regenerate with: npm run gen
// Enums: ref/decompiled/VTClassic/*.cs. Tables: GameInfo in ref/shared/Constants.cs.

${enumText('intValueKey', parseEnum(vtclassic('IntValueKey.cs'), 'IntValueKey'))}
${enumText('doubleValueKey', parseEnum(vtclassic('DoubleValueKey.cs'), 'DoubleValueKey'))}
${enumText('stringValueKey', parseEnum(vtclassic('StringValueKey.cs'), 'StringValueKey'))}
${enumText('objectClass', parseEnum(vtclassic('ObjectClass.cs'), 'ObjectClass'))}
${enumText('vtcSkillID', parseEnum(vtclassic('VTCSkillID.cs'), 'VTCSkillID'))}
${pairTableText('setInfo', addPairs(methodBody(constants, 'getSetInfo')))}
${pairTableText('skillInfo', addPairs(methodBody(constants, 'getSkillInfo')))}
${pairTableText('masteryInfo', addPairs(methodBody(constants, 'getMasteryInfo')))}
${pairTableText('materialIds', materialIds)}
${nameTableText('materialNames', materialNames)}
${groupTableText('materialGroups', addGroups(methodBody(constants, 'getMaterialGroups')))}
`

writeFileSync(fileURLToPath(new URL('src/core/gamedata/generated.ts', root)), output)
console.log(`wrote src/core/gamedata/generated.ts (${output.split('\n').length} lines)`)
